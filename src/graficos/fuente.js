export const CARACTERES = Object.keys(GLIFOS).join('');
const CW = 4;
const CH = 6;

export function crearFuente(escena) {
  const { canvas, ctx } = lienzo(CW * CARACTERES.length, CH);
  [...CARACTERES].forEach((ch, i) => {
    const g = GLIFOS[ch];
    for (const [color, d] of [['#1a1420', 1], ['#ffffff', 0]]) {
      g.forEach((fila, y) => {
        [...fila].forEach((p, x) => {
          if (p === '#') px(ctx, color, i * CW + x + d, y + d, 1, 1);
        });
      });
    }
  });
  escena.textures.addCanvas('fuente', canvas);
  const datos = Phaser.GameObjects.RetroFont.Parse(escena, {
    image: 'fuente',
    width: CW,
    height: CH,
    chars: CARACTERES,
    charsPerRow: CARACTERES.length,
    spacing: { x: 0, y: 0 },
    offset: { x: 0, y: 0 },
    lineSpacing: 0
  });
  escena.cache.bitmapFont.add('fuente', datos);
}

export function textoFuente(texto) {
  return String(texto)
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toUpperCase()
    .split('')
    .map((c) => (GLIFOS[c] ? c : ' '))
    .join('');
}
